// Start launches the background worker loop.
func (d *Dispatcher) Start() {
	d.wg.Add(1)
	go d.workerLoop()
}

// Stop gracefully shuts down the worker.
func (d *Dispatcher) Stop() {
	close(d.stopChan)
	d.wg.Wait()
}

func (d *Dispatcher) workerLoop() {
	defer d.wg.Done()
	ticker := time.NewTicker(d.pollInterval)
	defer ticker.Stop()

	for {
		select {
		case <-d.stopChan:
			return
		case <-ticker.C:
			d.processPendingEvents()
		}
	}
}

// ProcessPendingEvents manually executes a processing cycle (public for tests).
func (d *Dispatcher) ProcessPendingEvents() {
	d.processPendingEvents()
}

func (d *Dispatcher) processPendingEvents() {
	if d.db == nil {
		return
	}

	var events []models.OutboxEvent
	now := time.Now()
	leaseUntil := now.Add(2 * time.Minute)

	// Claim a batch atomically. The row locks plus conditional UPDATE ensure
	// that two dispatchers (or two application instances) never process the
	// same event concurrently. A crashed worker's lease expires and the event
	// becomes claimable again.
	err := d.db.Transaction(func(tx *gorm.DB) error {
		if err := tx.Clauses(clause.Locking{Strength: "UPDATE", Options: "SKIP LOCKED"}).
			Where("status IN ('pending', 'processing') AND retry_count < max_retries").
			Where("(locked_until IS NULL OR locked_until < ?)", now).
			Where("(available_at IS NULL OR available_at <= ?)", now).
			Order("created_at ASC").
			Limit(10).
			Find(&events).Error; err != nil {
			return err
		}
		if len(events) == 0 {
			return nil
		}
		ids := make([]uint, 0, len(events))
		for _, event := range events {
			ids = append(ids, event.ID)
		}
		if err := tx.Model(&models.OutboxEvent{}).
			Where("id IN ?", ids).
			Updates(map[string]interface{}{
				"status":       "processing",
				"locked_until": leaseUntil,
			}).Error; err != nil {
			return err
		}
		for i := range events {
			events[i].Status = "processing"
			events[i].LockedUntil = &leaseUntil
		}
		return nil
	})

	if err != nil || len(events) == 0 {
		return
	}

	for _, event := range events {
		d.processSingleEvent(event)
	}
}

func (d *Dispatcher) processSingleEvent(event models.OutboxEvent) {
	var procErr error

	switch event.EventType {
	case "telegram_notification":
		var p TelegramNotificationPayload
		if err := json.Unmarshal([]byte(event.Payload), &p); err != nil {
			procErr = err
		} else if d.notifyFunc != nil {
			procErr = d.notifyFunc(p.TelegramID, p.Message)
		}
	case "admin_receipt_card":
		var p AdminAlertPayload
		if err := json.Unmarshal([]byte(event.Payload), &p); err != nil {
			procErr = err
		} else if d.sendReceiptCardFunc != nil {
			procErr = d.sendReceiptCardFunc(p.AdminTelegramID, p)
		}
	case "payment_notice":
		var p PaymentNoticePayload
		if err := json.Unmarshal([]byte(event.Payload), &p); err != nil {
			procErr = err
		} else if d.paymentNoticeFunc != nil {
			procErr = d.paymentNoticeFunc(p)
		}
	default:
		procErr = fmt.Errorf("unknown outbox event type: %s", event.EventType)
	}

	now := time.Now()
	if d.db != nil {
		if procErr == nil {
			_ = d.db.Model(&models.OutboxEvent{}).Where("id = ?", event.ID).Updates(map[string]interface{}{
				"status":       "completed",
				"processed_at": &now,
				"last_error":   "",
				"locked_until": nil,
			})
		} else {
			newCount := event.RetryCount + 1
			newStatus := "pending"
			if newCount >= event.MaxRetries {
				newStatus = "failed"
			}
			// Exponential backoff: 30s, 1m, 2m, 4m ... capped at one hour.
			backoff := time.Duration(1<<uint(newCount)) * 30 * time.Second
			if backoff > time.Hour || backoff <= 0 {
				backoff = time.Hour
			}
			availableAt := now.Add(backoff)
			_ = d.db.Model(&models.OutboxEvent{}).Where("id = ?", event.ID).Updates(map[string]interface{}{
				"status":       newStatus,
				"retry_count":  newCount,
				"last_error":   procErr.Error(),
				"available_at": &availableAt,
				"locked_until": nil,
			})
			log.Printf("[Outbox] Failed delivering event #%d (%s): %v. Retry %d/%d",
				event.ID, event.EventType, procErr, newCount, event.MaxRetries)
		}
	}
}
