package outbox

import (
	"encoding/json"
	"fmt"
	"log"
	"sync"
	"time"

	"github.com/spark-school/backend/internal/models"
	"gorm.io/gorm"
	"gorm.io/gorm/clause"
)

// TelegramNotificationPayload structure serialized into outbox payload.
type TelegramNotificationPayload struct {
	TelegramID int64  `json:"telegram_id"`
	Message    string `json:"message"`
}

// AdminAlertPayload structure for receipt cards and system alerts.
type AdminAlertPayload struct {
	AdminTelegramID int64   `json:"admin_telegram_id"`
	ReceiptID       uint    `json:"receipt_id"`
	StudentName     string  `json:"student_name"`
	Username        string  `json:"username"`
	Amount          float64 `json:"amount"`
	Tier            string  `json:"tier"`
	FileID          string  `json:"file_id,omitempty"`
}

// PaymentNoticePayload is delivered after a payment transaction commits. The
// invite link is generated by the worker at delivery time, never inside the
// financial transaction.
type PaymentNoticePayload struct {
	Kind       string  `json:"kind"` // access, upgrade, audit, admin
	TelegramID int64   `json:"telegram_id"`
	PaymentID  string  `json:"payment_id"`
	Tier       string  `json:"tier"`
	Amount     float64 `json:"amount"`
	Username   string  `json:"username,omitempty"`
	PromoCode  string  `json:"promo_code,omitempty"`
	Source     string  `json:"source,omitempty"`
	AdminID    int64   `json:"admin_id,omitempty"`
}

// Dispatcher processes queued Outbox events with retries and exponential backoff.
type Dispatcher struct {
	db                  *gorm.DB
	notifyFunc          func(telegramID int64, message string) error
	sendReceiptCardFunc func(adminID int64, payload AdminAlertPayload) error
	paymentNoticeFunc   func(payload PaymentNoticePayload) error
	pollInterval        time.Duration
	stopChan            chan struct{}
	wg                  sync.WaitGroup
}

// NewDispatcher creates a new Outbox Dispatcher.
func NewDispatcher(
	db *gorm.DB,
	notifyFunc func(telegramID int64, message string) error,
	sendReceiptCardFunc func(adminID int64, payload AdminAlertPayload) error,
	paymentNoticeFuncs ...func(payload PaymentNoticePayload) error,
) *Dispatcher {
	var paymentNoticeFunc func(payload PaymentNoticePayload) error
	if len(paymentNoticeFuncs) > 0 {
		paymentNoticeFunc = paymentNoticeFuncs[0]
	}
	return &Dispatcher{
		db:                  db,
		notifyFunc:          notifyFunc,
		sendReceiptCardFunc: sendReceiptCardFunc,
		paymentNoticeFunc:   paymentNoticeFunc,
		pollInterval:        2 * time.Second,
		stopChan:            make(chan struct{}),
	}
}

// EnqueueNotificationTx enqueues a telegram notification inside an active database transaction.
func EnqueueNotificationTx(tx *gorm.DB, telegramID int64, message string) error {
	if tx == nil {
		return fmt.Errorf("transaction is nil")
	}
	payloadBytes, err := json.Marshal(TelegramNotificationPayload{
		TelegramID: telegramID,
		Message:    message,
	})
	if err != nil {
		return fmt.Errorf("failed to marshal notification payload: %w", err)
	}

	event := models.OutboxEvent{
		EventType:  "telegram_notification",
		Payload:    string(payloadBytes),
		Status:     "pending",
		CreatedAt:  time.Now(),
		MaxRetries: 5,
	}

	return tx.Create(&event).Error
}

